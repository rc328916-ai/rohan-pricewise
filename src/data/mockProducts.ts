// Helper to generate realistic 7-day history leading up to today's price
function generateHistory(
  todayPrice: number,
  pattern: 'dropping' | 'rising' | 'lowest-today' | 'steady' | 'volatile',
  variance: number = 0.05
) {
  const dates = [
    { offset: -7, label: '7d ago', date: 'Nov 5' },
    { offset: -6, label: '6d ago', date: 'Nov 6' },
    { offset: -5, label: '5d ago', date: 'Nov 7' },
    { offset: -4, label: '4d ago', date: 'Nov 8' },
    { offset: -3, label: '3d ago', date: 'Nov 9' },
    { offset: -2, label: '2d ago', date: 'Nov 10' },
    { offset: -1, label: 'Yesterday', date: 'Nov 11' },
    { offset: 0, label: 'Today', date: 'Nov 12' },
  ];

  const multipliers: Record<string, number[]> = {
    'lowest-today': [1.12, 1.10, 1.09, 1.07, 1.06, 1.04, 1.02, 1.0],
    'dropping': [1.08, 1.07, 1.08, 1.05, 1.04, 1.03, 1.01, 1.0],
    'rising': [0.93, 0.94, 0.94, 0.96, 0.97, 0.98, 0.99, 1.0],
    'steady': [1.01, 1.0, 1.0, 1.01, 1.0, 0.99, 1.0, 1.0],
    'volatile': [1.06, 1.02, 1.08, 0.97, 1.04, 0.98, 1.02, 1.0],
  };

  const chosenMultipliers = multipliers[pattern] || multipliers['steady'];

  return dates.map((d, index) => {
    const raw = Math.round(todayPrice * chosenMultipliers[index]);
    // round to nearest 10 or 99
    const rounded = Math.round(raw / 10) * 10 - 1;
    return {
      dayOffset: d.offset,
      dayLabel: d.label,
      date: d.date,
      price: index === 7 ? todayPrice : (rounded < 100 ? raw : rounded),
    };
  });
}

